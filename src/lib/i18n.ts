const DICTS: Record<Lang, Dict> = { en, fil };

let lang: Lang = "fil";
let currency: Currency = "PHP";

export function configure(settings: { language?: Lang; currency?: Currency }) {
  lang = settings.language ?? "fil";
  currency = settings.currency ?? "PHP";
}

export const t = () => DICTS[lang];

export const locale = () => (lang === "en" ? (currency === "USD" ? "en-US" : "en-PH") : "en-PH");

export const formatMoney = (n: number) =>
  new Intl.NumberFormat(locale(), { style: "currency", currency, minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(n);

export const currencySymbol = () => (currency === "USD" ? "$" : "₱");
